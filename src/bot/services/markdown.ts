/**
 * Экранирование текста, который подставляется в сообщения с
 * `parse_mode: 'Markdown'`.
 *
 * Telegram считает `_ * \` [` управляющими символами, а имена проектов и
 * заголовки задач приходят от пользователя и из Трекера. Одного `open_line`
 * в списке проектов хватало, чтобы вся отправка падала с 400 «can't parse
 * entities: can't find end of the entity» — и бот молча переставал отвечать
 * на /projects: ошибка видна только в логах функции.
 *
 * Экранируем именно подставляемые значения, а не готовую строку: разметка
 * вокруг них (`**жирный**`) должна остаться разметкой.
 */
export function escapeMarkdown(text: string): string {
  return text.replace(/([_*`[\]])/g, '\\$1')
}
